export function getRoute(slug = ""): ThemeRoute {
  const normalized = slug.replace(/^\/+|\/+$/g, "");
  const route = routes.find((item) => item.slug === normalized);
  if (!route) {
    throw new Error(`Unknown route: ${slug}`);
  }
  return route;
}
